export function getCreatureById(id: string): Creature | undefined {
  return creatures.find((c) => c.id === id)
}

export function getCreaturesByLevel(minLevel: number, maxLevel: number): Creature[] {
  return creatures.filter((c) => c.level >= minLevel && c.level <= maxLevel)
}

export function getRandomCreature(level: number): Creature {
  const range = 2
  const possibleCreatures = getCreaturesByLevel(Math.max(1, level - range), level + range)
  const selected = possibleCreatures[Math.floor(Math.random() * possibleCreatures.length)]

  // Cria uma cópia profunda para resetar HP e stats
  return {
    ...selected,
    stats: { ...selected.stats, hp: selected.stats.maxHp },
    attacks: selected.attacks.map((a) => ({ ...a })),
  }
}
